def generate_splits(test_size=0.25, random_state=42):
    base_dir = os.path.dirname(os.path.abspath(__file__))
    all_examples = []
    all_labels = []

    for intent, examples in INTENT_DATA.items():
        for text in examples:
            all_examples.append(text)
            all_labels.append(intent)

    X_train, X_test, y_train, y_test = train_test_split(
        all_examples,
        all_labels,
        test_size=test_size,
        random_state=random_state,
        stratify=all_labels
    )

    train_data = [{"text": text, "intent": label} for text, label in zip(X_train, y_train)]
    test_data = [{"text": text, "intent": label} for text, label in zip(X_test, y_test)]

    train_path = os.path.join(base_dir, "training_data.json")
    test_path = os.path.join(base_dir, "test_data.json")

    with open(train_path, "w", encoding="utf-8") as f:
        json.dump(train_data, f, indent=2)

    with open(test_path, "w", encoding="utf-8") as f:
        json.dump(test_data, f, indent=2)

    print(f"Generated {len(train_data)} training examples and {len(test_data)} test examples.")
    print(f"Intents ({len(INTENT_DATA)}): {list(INTENT_DATA.keys())}")
    return train_path, test_path

if __name__ == "__main__":
    generate_splits()
